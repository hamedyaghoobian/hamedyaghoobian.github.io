"""
Builds assets/js/masfin-data.js for the MASFIN project page's figure: the
eight live weeks' holdings (ticker → allocation %) and weekly returns of
MASFIN and the three indexes, from the project's own sheets.

    python3 scripts/masfin_data.py ~/LargerProjects/MASFIN-main
"""
import csv
import json
import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1])
OUT = Path(__file__).resolve().parent.parent / "assets/js/masfin-data.js"

weeks, cur = [], None
for r in csv.reader(open(SRC / "portfolio.csv", encoding="utf-8-sig")):
    if r and re.match(r"Week \d", r[0]):
        cur = {}
        weeks.append(cur)
    elif cur is not None and r and r[0].strip() not in ("", "Ticker", "Total") and r[1].strip().endswith("%"):
        cur[r[0].strip()] = float(r[1].strip().rstrip("%"))

dates, ret = [], {k: [] for k in ("MASFIN", "S&P 500", "NASDAQ-100", "Dow Jones")}
for r in csv.reader(open(SRC / "masfin_data.csv", encoding="utf-8-sig")):
    if len(r) > 5 and re.match(r"Week \d", r[1] or ""):
        dates.append(r[0].strip())
        for k, col in (("NASDAQ-100", 2), ("S&P 500", 3), ("Dow Jones", 4), ("MASFIN", 5)):
            ret[k].append(float(r[col].strip().rstrip("%")))

assert len(weeks) == len(dates) == 8, (len(weeks), len(dates))
OUT.write_text("// Generated by scripts/masfin_data.py from the MASFIN project's portfolio and returns sheets.\n"
               "window.MASFIN = " + json.dumps({"dates": dates, "holdings": weeks, "returns": ret}, separators=(",", ":")) + ";\n")
print("wrote", OUT, sum(len(w) for w in weeks), "holdings")
