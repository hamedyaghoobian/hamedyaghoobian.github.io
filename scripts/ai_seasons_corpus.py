"""
Builds assets/js/ai-seasons-corpus.js for the AI Seasons project page's
figure: how many documents the 2024 scrapers gathered from each source in
each year, and how many words. Counts only; no text leaves the corpus.

    python3 scripts/ai_seasons_corpus.py ~/LargerProjects/ai-seasons-ant
"""
import json
import sys
from pathlib import Path

import pandas as pd

SRC = Path(sys.argv[1]) / "data/corpus/corpus.parquet"
OUT = Path(__file__).resolve().parent.parent / "assets/js/ai-seasons-corpus.js"
NAMES = {"verge": "The Verge", "tnw": "The Next Web", "pmc": "PubMed Central", "lifewire": "Lifewire",
         "techcrunch": "TechCrunch", "youtube": "YouTube", "arxiv": "arXiv"}

d = pd.read_parquet(SRC, columns=["source", "year", "text"])
d["words"] = d.text.fillna("").str.split().str.len()
sources = []
for key, g in d.groupby("source"):
    by = g.dropna(subset=["year"]).groupby("year").size()
    sources.append({"key": key, "name": NAMES[key], "docs": int(len(g)), "words": int(g.words.sum()),
                    "undated": int(g.year.isna().sum()), "years": {int(y): int(n) for y, n in by.items()}})
sources.sort(key=lambda s: -s["docs"])

OUT.write_text("// Generated by scripts/ai_seasons_corpus.py from the AI Seasons corpus (counts only). Do not edit by hand.\n"
               "window.AISEASONS_CORPUS = " + json.dumps({"sources": sources}, separators=(",", ":")) + ";\n")
print("wrote", OUT, sum(s["docs"] for s in sources), "docs", sum(s["words"] for s in sources), "words")
